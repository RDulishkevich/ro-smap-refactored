export const DICT = { ru, en };

export type I18nKey = keyof typeof ru;

export function typeI18nKey(type: string): I18nKey {
  if (type === 'nature') return 'typeNature';
  if (type === 'water') return 'typeWater';
  if (type === 'urban') return 'typeUrban';
  if (type === 'forest') return 'typeForest';
  if (type === 'birds') return 'typeBirds';
  return 'typeOther';
}

export function kindI18nKey(kind: string): I18nKey {
  if (kind === 'sound') return 'kindSound';
  if (kind === 'expedition') return 'kindExpedition';
  if (kind === 'event') return 'kindEvent';
  if (kind === 'person') return 'kindPerson';
  return 'kindPost';
}

export function recordingsLabel(n: number, t: (k: I18nKey) => string, locale: Locale) {
  if (locale === 'en') return n === 1 ? t('recordingOne') : t('recordingMany');
  const m = n % 100;
  if (m >= 11 && m <= 14) return t('recordingMany');
  const d = n % 10;
  if (d === 1) return t('recordingOne');
  if (d >= 2 && d <= 4) return t('recordingFew');
  return t('recordingMany');
}
